// `bazel run //typescript:node_modules_link`: links each workspace package's node_modules in the
// source tree to the one Bazel builds, so IDEs resolve imports without a pnpm install. Workspace
// packages resolve to their built `:pkg`. A node_modules that is a real directory (from pnpm
// install) is left alone.

import { lstatSync, rmSync, symlinkSync } from "node:fs";
import { join } from "node:path";

const bindir = join(process.env.JS_BINARY__EXECROOT, process.env.JS_BINARY__BINDIR);
const workspace = process.env.BUILD_WORKSPACE_DIRECTORY;

for (const dir of process.argv.slice(2)) {
  const link = join(workspace, dir, "node_modules");
  const target = join(bindir, dir, "node_modules");
  let existing;
  try {
    existing = lstatSync(link);
  } catch {
    existing = undefined;
  }
  if (existing && !existing.isSymbolicLink()) {
    console.log(`kept ${join(dir, "node_modules")}: a directory, not a link`);
    continue;
  }
  if (existing) rmSync(link);
  symlinkSync(target, link);
  console.log(`${join(dir, "node_modules")} -> ${target}`);
}
