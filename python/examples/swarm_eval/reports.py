"""The eval swarm's results as data and as markdown: the report a run replies with, and the pages
the dispatcher's `report`, `case` and `suites` handlers show in the console's chat."""

from __future__ import annotations

from collections import Counter
from datetime import datetime, timezone

from examples.swarm_eval.categories import BY_KEY, CATEGORIES
from examples.swarm_eval.library import Catalog, CaseOutcome, RunRecord
from examples.swarm_eval.models import (
    CaseResult,
    Category,
    CategoryResult,
    Comparison,
    EvalCase,
    EvalReport,
    Failure,
)

MAX_FAILURES = 10


def build_report(
    *,
    run_id: str,
    suite: str,
    swarm_id: str,
    target: str,
    results: list[CaseResult],
    agents_started: int,
    seconds: float,
    failed_batches: int = 0,
    comparison: Comparison | None = None,
    categories: list[Category] | tuple[Category, ...] = CATEGORIES,
    simulate: bool = False,
) -> EvalReport:
    """The run's report: pass rate overall and per category, failure modes, worst failures, and
    how it compares with the suite's previous run."""
    passed = sum(r.verdict.passed for r in results)
    by_category = []
    for category in categories:
        mine = [r for r in results if r.category == category.key]
        if mine:
            by_category.append(
                CategoryResult(
                    category=category.key,
                    title=category.title,
                    passed=sum(r.verdict.passed for r in mine),
                    total=len(mine),
                )
            )
    failed = sorted(
        (r for r in results if not r.verdict.passed), key=lambda r: (r.verdict.score, r.case_id)
    )
    failures = [
        Failure(
            case_id=r.case_id,
            category=r.category,
            failure_mode=r.verdict.failure_mode,
            summary=r.verdict.summary,
            target_workflow_id=r.target_workflow_id,
        )
        for r in failed[:MAX_FAILURES]
    ]
    modes = dict(Counter(r.verdict.failure_mode for r in failed).most_common())
    rate = passed / len(results) if results else 0.0
    mean = sum(r.verdict.score for r in results) / len(results) if results else 0.0

    lines = [
        "## Simulation complete" if simulate else "## Evaluation results",
        "",
        f"**{passed} of {len(results)} scenarios passed; {len(failed)} failed.** "
        f"Target: `{target}`.",
        "",
        (
            "This was a practice run of the evaluation system with scripted agents and no model API calls. "
            "Pass/fail decisions and scores are generated by the simulator; they do not measure "
            "model quality or product fit. Simulated verdicts include failures to exercise reporting."
            if simulate else
            "These results describe the target's behavior on this test suite. "
            "Passing these tests alone does not establish product fit or declare the product ready."
        ),
        "",
        "### What happened",
        "",
        f"- Ran {len(results)} scenarios across {len(by_category)} categories, each against a fresh target agent.",
        f"- Collected conversations and tool calls, then graded the results: {rate:.1%} passed, "
        f"with an average score of {mean:.1f}/5.",
        f"- Started {agents_started} agents over {seconds:.1f} seconds. "
        "This total includes case writers, category leads, testers, target agents, and judges; "
        "it is not the number running at once or a count of product ideas.",
        f"- Case-writing batches that failed: {failed_batches}.",
    ]
    if comparison:
        lines += ["", *comparison_lines(comparison)]
    lines += [
        "",
        "### Results by category",
        "",
        "| Category | Passed |",
        "| --- | --- |",
        *(f"| {c.title} | {c.passed}/{c.total} |" for c in by_category),
    ]
    if modes:
        lines += ["", "**Failure modes:** " + ", ".join(f"{m} ({n})" for m, n in modes.items())]
    if failures:
        lines += ["", "### Failures to inspect", ""]
        lines += [f"- `{f.case_id}` ({f.failure_mode}): {f.summary}" for f in failures]
    lines += [
        "",
        "### What to do next",
        "",
        (
            "Choose a real product candidate, configure its target and evaluation profile, "
            "and run with **Simulate off**. Then gather evidence from intended users to assess product fit. "
            "This simulation does not declare readiness or move anything from examples to products."
            if simulate else
            "Inspect the failures, improve the target, and rerun the saved suite to check for regressions. "
            "Combine these technical results with evidence from intended users before declaring readiness."
        ),
        "",
        "Send `report` for each failure's evidence, `case` with a case id for one case in full, "
        f'or `evaluate` with `suite: "{suite}"` to run these same cases again after a change.',
        "",
        f"Run: `{run_id}`.",
    ]

    return EvalReport(
        run_id=run_id,
        suite=suite,
        comparison=comparison,
        swarm_id=swarm_id,
        target=target,
        cases=len(results),
        passed=passed,
        pass_rate=round(rate, 4),
        mean_score=round(mean, 2),
        by_category=by_category,
        failure_modes=modes,
        failures=failures,
        agents_started=agents_started,
        seconds=round(seconds, 1),
        failed_batches=failed_batches,
        markdown="\n".join(lines),
    )


def comparison_lines(comparison: Comparison) -> list[str]:
    delta = comparison.pass_rate_delta
    trend = "up" if delta > 0 else "down" if delta < 0 else "unchanged"
    lines = [
        f"**Against `{comparison.previous_run_id}`:** pass rate {trend} "
        f"({comparison.previous_pass_rate:.0%} → {comparison.previous_pass_rate + delta:.0%}); "
        f"{len(comparison.fixed)} fixed, {len(comparison.regressed)} regressed, "
        f"{len(comparison.still_failing)} still failing."
    ]
    if comparison.regressed:
        lines.append("Regressed: " + ", ".join(f"`{c}`" for c in comparison.regressed))
    if comparison.fixed:
        lines.append("Fixed: " + ", ".join(f"`{c}`" for c in comparison.fixed))
    return lines


def run_record(report: EvalReport, results: list[CaseResult], models: dict[str, str], finished_at: float) -> RunRecord:
    return RunRecord(
        run_id=report.run_id,
        suite=report.suite,
        target=report.target,
        finished_at=finished_at,
        models=models,
        pass_rate=report.pass_rate,
        mean_score=report.mean_score,
        outcomes={
            r.case_id: CaseOutcome(
                passed=r.verdict.passed, score=r.verdict.score, failure_mode=r.verdict.failure_mode
            )
            for r in results
        },
    )


def _clip(text: str, limit: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else f"{text[: limit - 1]}…"


def failure_evidence(result: CaseResult, case: EvalCase) -> list[str]:
    """A failure in a few lines: what the user wanted, what was unmet, and the tools that ran."""
    unmet = [c for c in result.verdict.criteria if not c.met]
    lines = [
        f"### `{result.case_id}` — {result.verdict.failure_mode}, score {result.verdict.score}/5",
        "",
        f"{result.verdict.summary}",
        "",
        f"**Goal:** {_clip(case.goal, 240)}",
    ]
    for criterion in unmet[:3]:
        lines.append(f"- ✗ {_clip(criterion.criterion, 120)} — {_clip(criterion.evidence, 200)}")
    if result.error:
        lines.append(f"- **Error:** {_clip(result.error, 240)}")
    if result.tool_calls:
        calls = ", ".join(
            f"`{c.name}`" + (" (error)" if c.error else "") for c in result.tool_calls[:12]
        )
        lines.append(f"- **Tools:** {calls}")
    else:
        lines.append("- **Tools:** none")
    return lines


def render_run(
    report: EvalReport, results: dict[str, CaseResult], cases: dict[str, EvalCase]
) -> str:
    """The `report` page: the report, then every failure's evidence (regressions first)."""
    regressed = set(report.comparison.regressed) if report.comparison else set()
    failed = sorted(
        (r for r in results.values() if not r.verdict.passed),
        key=lambda r: (r.case_id not in regressed, r.verdict.score, r.case_id),
    )
    lines = [report.markdown]
    if failed:
        lines += ["", "---", "", "## Failures", ""]
        for result in failed:
            if result.case_id in regressed:
                lines.append("**Regressed** since the previous run.")
            lines += [*failure_evidence(result, cases[result.case_id]), ""]
    return "\n".join(lines)


def render_case(case: EvalCase, result: CaseResult) -> str:
    """The `case` page: everything one case was graded on."""
    verdict = result.verdict
    lines = [
        f"## `{case.id}` — {'passed' if verdict.passed else 'failed'} ({verdict.score}/5)",
        "",
        f"**Category:** {BY_KEY[case.category].title if case.category in BY_KEY else case.category} · **Persona:** {case.persona}",
        "",
        f"**Goal:** {case.goal}",
        "",
        f"**Verdict:** {verdict.summary}",
        "",
        "| Criterion | Met | Evidence |",
        "| --- | --- | --- |",
        *(
            f"| {_clip(c.criterion, 100)} | {'✓' if c.met else '✗'} | {_clip(c.evidence, 160)} |"
            for c in verdict.criteria
        ),
        "",
        "### Conversation",
        "",
    ]
    for exchange in result.conversation:
        lines += [f"> **User:** {exchange.user}", ">", f"> **Agent:** {exchange.agent}", ""]
    if result.error:
        lines += [f"**Ended with an error:** {result.error}", ""]
    lines += ["### Tool calls", ""]
    if not result.tool_calls:
        lines.append("None.")
    for i, call in enumerate(result.tool_calls, 1):
        outcome = f"error: {call.error}" if call.error else (call.output or "")
        lines += [f"{i}. `{call.name}` — {_clip(call.input, 300)}", f"   → {_clip(outcome, 300)}"]
    lines += ["", f"Target workflow: `{result.target_workflow_id}`"]
    return "\n".join(lines)


def render_catalog(catalog: Catalog, target: str) -> str:
    """The `suites` page: saved suites and recent runs for one target."""

    def when(ts: float) -> str:
        return datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [f"## Saved suites for {target}", ""]
    if not catalog.suites:
        lines.append("None yet. Every `evaluate` saves the cases it writes.")
    lines += [f"- `{s.name}`: {s.cases} cases, saved {when(s.created_at)}" for s in catalog.suites]
    lines += ["", "## Recent runs", ""]
    if not catalog.runs:
        lines.append("None yet.")
    else:
        lines += ["| Run | Suite | Passed | Mean score | Finished |", "| --- | --- | --- | --- | --- |"]
        lines += [
            f"| `{r.run_id}` | `{r.suite}` | {r.pass_rate:.0%} | {r.mean_score:.1f} | {when(r.finished_at)} |"
            for r in catalog.runs
        ]
    return "\n".join(lines)
