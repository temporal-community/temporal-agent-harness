"""Writes an agents.toml registry for harness_agent_registry (bazel/agents.bzl).

    agents_toml <spec.json> <out.toml>

The spec lists each agent's registry fields and its schema document. Each entry's
``workflow_type`` is the workflow its schema describes, and its ``schema`` is that document's
file name, which the registry's update target writes beside agents.toml.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def _string(value: str) -> str:
    # A JSON string is a valid TOML basic string.
    return json.dumps(value, ensure_ascii=False)


def _multiline(value: str) -> str:
    escaped = value.strip().replace("\\", "\\\\").replace('"', '\\"')
    return '"""\n' + escaped + '"""'


def main(spec_path: Path, out_path: Path) -> None:
    spec = json.loads(spec_path.read_text())
    lines = [
        f"# GENERATED by {spec['registry']} (harness_agent_registry). Do not edit: change its",
        f"# harness_agent targets, then `bazel run {spec['update']}`.",
    ]
    for agent in spec["agents"]:
        document = json.loads(Path(agent["schema_path"]).read_text())
        lines += [
            "",
            "[[agents]]",
            f"key = {_string(agent['key'])}",
            f"workflow_type = {_string(document['agent'])}",
            f"task_queue = {_string(agent['task_queue'])}",
            f"label = {_string(agent['label'])}",
            f"schema = {_string(agent['schema'])}",
            f"description = {_multiline(agent['description'])}",
        ]
    out_path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
